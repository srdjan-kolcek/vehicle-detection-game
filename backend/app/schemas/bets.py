import uuid
from decimal import Decimal
from typing import Literal

from pydantic import BaseModel, Field

Choice = Literal["under", "exact", "over"]


class BetRequest(BaseModel):
    bet_id: uuid.UUID  # generated by the client; resubmitting it is safe
    choice: Choice
    stake: int = Field(gt=0, strict=True)  # minor units


class BetResponse(BaseModel):
    bet_id: uuid.UUID
    round_id: int
    choice: Choice
    stake: int  # minor units
    multiplier: Decimal
    status: str
    balance: int  # player's balance after the bet, minor units
